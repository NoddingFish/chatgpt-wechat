SET NAMES 'utf8';
CREATE TABLE IF NOT EXISTS `transfer_log`
(
    `id`                     bigint unsigned NOT NULL AUTO_INCREMENT,
    `transfer_id`            varchar(64) COLLATE utf8mb4_unicode_ci                        NOT NULL COMMENT '转人工唯一标识(UUID)',
    `user_id`                varchar(191) COLLATE utf8mb4_unicode_ci                       NOT NULL COMMENT '用户ID',
    `user_type`              varchar(20) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT 'customer' COMMENT '用户类型: wecom/customer',
    `agent_id`               bigint unsigned                                               NOT NULL DEFAULT 0 COMMENT '应用ID',
    `open_kf_id`             varchar(191) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT '' COMMENT '客服ID',
    `request_id`             varchar(64) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT '' COMMENT '关联请求ID',
    `transfer_reason`        varchar(200) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT '' COMMENT '转人工原因',
    `user_message`           text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci        NOT NULL COMMENT '用户触发转人工的消息内容',
    `service_state`          int                                                           NOT NULL DEFAULT 2 COMMENT '服务状态: 0-未处理 1-AI接待 2-排队中 3-人工接待',
    `assigned_servicer_id`   varchar(100) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT '' COMMENT '分配的接待人员ID',
    `assignment_type`        varchar(20) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT 'round_robin' COMMENT '分配方式: round_robin/direct/fallback',
    `was_in_working_hours`   tinyint(1)                                                    NOT NULL DEFAULT 1 COMMENT '是否在工作时间内',
    `transfer_status`        varchar(20) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT 'pending' COMMENT '转人工状态: pending/accepted/timeout/cancelled',
    `accepted_at`            timestamp NULL DEFAULT NULL COMMENT '客服接受时间',
    `wait_duration_ms`       int                                                           NOT NULL DEFAULT 0 COMMENT '排队等待时长(毫秒)',
    `session_end_at`         timestamp NULL DEFAULT NULL COMMENT '会话结束时间',
    `session_duration_ms`    int                                                           NOT NULL DEFAULT 0 COMMENT '会话总时长(毫秒)',
    `transfer_success`       tinyint(1)                                                    NOT NULL DEFAULT 0 COMMENT '转人工是否成功',
    `error_msg`              text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci                 COMMENT '错误信息',
    `webhook_notified`       tinyint(1)                                                    NOT NULL DEFAULT 0 COMMENT '是否已发送webhook通知',
    `created_at`             timestamp                                                     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at`             timestamp                                                     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_transfer_id` (`transfer_id`) USING BTREE,
    KEY `idx_user_id` (`user_id`) USING BTREE,
    KEY `idx_agent_id` (`agent_id`) USING BTREE,
    KEY `idx_open_kf_id` (`open_kf_id`) USING BTREE,
    KEY `idx_request_id` (`request_id`) USING BTREE,
    KEY `idx_transfer_status` (`transfer_status`) USING BTREE,
    KEY `idx_created_at` (`created_at`) USING BTREE,
    KEY `idx_user_created` (`user_id`, `created_at`) USING BTREE,
    KEY `idx_kf_created` (`open_kf_id`, `created_at`) USING BTREE
) ENGINE=InnoDB COMMENT="转人工记录表" AUTO_INCREMENT=1 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
