SET NAMES 'utf8';
CREATE TABLE IF NOT EXISTS `request_log`
(
    `id`                  bigint unsigned NOT NULL AUTO_INCREMENT,
    `request_id`          varchar(64) COLLATE utf8mb4_unicode_ci                        NOT NULL COMMENT '请求唯一标识(UUID)',
    `request_type`        varchar(20) COLLATE utf8mb4_unicode_ci                       NOT NULL COMMENT '请求类型: ai_chat/transfer_op/command_op/human_chat',
    `user_id`             varchar(191) COLLATE utf8mb4_unicode_ci                       NOT NULL COMMENT '用户ID',
    `user_type`           varchar(20) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT 'customer' COMMENT '用户类型: wecom/customer',
    `agent_id`            bigint unsigned                                               NOT NULL DEFAULT 0 COMMENT '应用ID',
    `channel`             varchar(50) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT '' COMMENT 'AI渠道',
    `model_name`          varchar(100) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT '' COMMENT '模型名称',
    `req_content`         text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci        NOT NULL COMMENT '用户发送内容',
    `req_content_length`  int                                                           NOT NULL DEFAULT 0 COMMENT '请求内容长度',
    `is_voice`            tinyint(1)                                                    NOT NULL DEFAULT 0 COMMENT '是否为语音请求',
    `res_content`         text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci        NOT NULL COMMENT 'AI响应内容',
    `res_content_length`  int                                                           NOT NULL DEFAULT 0 COMMENT '响应内容长度',
    `status`              varchar(20) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT 'success' COMMENT '处理状态: success/failed/timeout',
    `error_msg`           text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci                 COMMENT '错误信息',
    `latency_ms`          int                                                           NOT NULL DEFAULT 0 COMMENT '响应耗时(毫秒)',
    `prompt_tokens`       int                                                           NOT NULL DEFAULT 0 COMMENT '消耗prompt token数',
    `completion_tokens`   int                                                           NOT NULL DEFAULT 0 COMMENT '消耗completion token数',
    `total_tokens`        int                                                           NOT NULL DEFAULT 0 COMMENT '总消耗token数',
    `conversation_id`     varchar(191) COLLATE utf8mb4_unicode_ci                       NOT NULL DEFAULT '' COMMENT '会话ID',
    `transfer_id`         varchar(64) COLLATE utf8mb4_unicode_ci                        NOT NULL DEFAULT '' COMMENT '关联转人工ID',
    `created_at`          timestamp                                                     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at`          timestamp                                                     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_request_id` (`request_id`) USING BTREE,
    KEY `idx_request_type` (`request_type`) USING BTREE,
    KEY `idx_user_id` (`user_id`) USING BTREE,
    KEY `idx_agent_id` (`agent_id`) USING BTREE,
    KEY `idx_channel` (`channel`) USING BTREE,
    KEY `idx_status` (`status`) USING BTREE,
    KEY `idx_created_at` (`created_at`) USING BTREE,
    KEY `idx_user_created` (`user_id`, `created_at`) USING BTREE,
    KEY `idx_agent_created` (`agent_id`, `created_at`) USING BTREE,
    KEY `idx_type_created` (`request_type`, `created_at`) USING BTREE
) ENGINE=InnoDB COMMENT="请求记录表" AUTO_INCREMENT=1 DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
